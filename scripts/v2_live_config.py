"""Turn the cross-validated picks of experiments_v2.py into a config for the live search path.

The live system uses one setting, the mean of the two folds' picks (nothing is tuned on the evaluated queries
beyond what CV already chose). Writes configs/v2_<dataset>_<encoder>.yaml for each encoder.

python scripts/v2_live_config.py --dataset flickr1k
"""

import argparse
import json
import re

import _bootstrap
import numpy as np
import yaml

from mmrag.config import resolve


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dataset", default="flickr1k")
    ap.add_argument("--tag", default="")
    args = ap.parse_args()
    res = json.loads(resolve(f"results/json/{args.dataset}_v2{args.tag}.json").read_text(encoding="utf-8"))
    for enc_short, folds in res["picked"].items():
        flat = res["live_flat_weights_suggestion"][enc_short]
        weights = {k: round(float(np.mean([f[k] for f in flat])), 3) for k in flat[0]}
        hub = [f.get("hub", [20.0, 0.0]) for f in folds]
        rr_key = f"{enc_short} final -> rerank ITM+ITC"
        rr = res["rerank_picks"].get(rr_key) or res["rerank_picks"].get(f"{enc_short} final -> rerank ITM")
        reranker = {}
        if rr:
            K = int(max(p[0] for p in rr))   # the larger pool of the two folds
            lam = [p[1] if isinstance(p[1], list) else [p[1], 0.0] for p in rr]
            reranker = {"top_k": K, "weight": round(float(np.mean([l[0] for l in lam])), 3),
                        "itc_weight": round(float(np.mean([l[1] for l in lam])), 3)}
        cfg = {"fusion": {"alpha": float(np.mean([f["alpha"] for f in folds])), "full_weights": weights,
                          "hub_beta": float(np.mean([h[0] for h in hub])), "hub_rho": float(np.mean([h[1] for h in hub]))},
               "reranker": reranker}
        full = res.get("encoder_short", {}).get(enc_short, enc_short)
        enc_slug = re.sub(r"[^a-zA-Z0-9]+", "-", full.split("/")[-1])
        out = resolve(f"configs/v2_{args.dataset}_{enc_slug}.yaml")
        out.write_text("# generated by scripts/v2_live_config.py from cross-validated picks (mean of the 2 folds)\n"
                       + yaml.safe_dump(cfg, sort_keys=False), encoding="utf-8")
        print(f"{out}:\n{yaml.safe_dump(cfg, sort_keys=False)}")


if __name__ == "__main__":
    main()
